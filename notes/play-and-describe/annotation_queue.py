#!/usr/bin/env python3
"""Which annotations has nobody acted on, and what does each one point at?

Question answered
-----------------
`tools/vm-debugger/rename_log.jsonl` is the only channel in this repository
through which a person who has **played** the game speaks: prose typed at the
screen while looking at one constant on one frame. Nothing in the tree reads it
back. Without a status an agent cannot tell a sentence that has already been
turned into names from one nobody has opened, and the two failures are
symmetric. Re-naming what is named is the failure `notes/unified-scoping/
applied_rows.tsv` exists to record -- a rename table is not idempotent and
cannot be made so, and a second run over an applied renumber spelled PRISON's
amiga pupil ladder `_1, _5, _6, _3, _4, _5`. Losing a sentence is worse: every
other thing this project reasons from can be regenerated by re-running
something, and a sentence cannot.

So the status is **derived from the tree** wherever the tree can carry it, and
asserted only where nothing in the tree can. Derived, per row, in two hops:
the token `annot:<id>` appears in the evidence cell of a proposal row under
`notes/`, and that row's new name is defined in `src/levels/<branch>/
<STAGE>.asm` as `NAME EQU` or `NAME:` -- the same adoption test
`sync_equ_rename.py` already uses. Per row rather than per table, so one
rejected row in a batch of twenty is visible instead of averaged away. Reading
the tree rather than an applier's stdout is also what catches the cartridge
silent no-op, which prints "N proposed, 0 rejected" while applying nothing
(`notes/HANDOFF.md`, "A rule learned the hard way"). The bookkeeping cannot
drift from the tree because it is read out of the tree on every run.

Statuses
--------
    PROPOSED   a row cites the id and the tree does not define its name: a
               rejected row or a half-applied batch. Work these FIRST -- a
               rename moves no bytes, so `make test` is blind to one, and this
               is how work gets lost.
    OPEN       nobody has cited it and nobody has ruled on it.
    AMENDED    no citation and no verdict, but another annotation on the same
               (branch, stage, target offset) is already settled: a second
               play session over an asset somebody finished.
    NAMED      every row citing it names something the tree now defines.
    CORROBORATES / NO_NAME / HELD / REJECTED
               hand-written in `verdicts.tsv`, one row per id. The only state
               here the tree cannot hold, and mutually exclusive with a
               citation: `--check` fails on an id carrying both.

A row whose new name is `SKIP` proposes nothing and is not a citation. A table
that looked and declined is an outcome, and outcomes go in `verdicts.tsv`.

The id
------
`ann:` + the first twelve hex of the sha1 of the annotation's raw log line,
newline stripped. One shell command, no tool and no index file:

    sed -n '1p' tools/vm-debugger/rename_log.jsonl | tr -d '\n' | sha1sum
    # cff7052605ce75f469b065bd08daf7c7ef7b5916   ->   ann:cff7052605ce

`--self-test` re-derives that value from the committed log. It is stable
because `server.py`'s only write is an append (`LOG.open("a")`), so an existing
line never changes; unaffected by reordering, unlike a line ordinal; not the
`at` timestamp, which has one-second resolution and comes from the appending
machine. The cost is a rule, and it is the whole cost of this scheme: **the log
is append-only.** Editing a line gives it a new id and orphans every table and
verdict that cited the old one -- reported by `--check` rather than silently
pointing at a sentence that no longer exists.

Nothing is called consumed out of a log only one machine has, either: while
`rename_log.jsonl` is dirty the queue says so at the top and `--check` fails if
any id is NAMED or verdicted. Commit the log first, alone and unedited -- step
0 of `README.md`.

Signal read
-----------
The queue line is status, id, branch/stage, frame, the target's current name
and offset, and the first clause of the sentence -- current name, read from the
`.asm` now, not the name the log recorded when it was typed.

`--measure` prints the sentence beside what the listing says, and the point of
it is that the two draw lists are not the same thing. The log's `routine_draws`
is **one frame's** draws filtered by routine: `siblingsOf` in
`tools/vm-debugger/static/app.js:91-96` filters `state.frame.draws`, so it
under-reports a run. `ann:cff7052605ce` carries one constant while
`STORM_AMBIENT_DRIFT_DRAW_LOOP` draws five --
`CINEMATIC_STORM_PARTICLE_F00..F04` at `x=[0x07], y=[0x09]`, one per `break`,
`INTRO.asm:1145-1153`. Taking the log field for the family would name a
five-frame run from a sample of one, so the static list is read out of the
`.asm` and printed beside it.

What this is NOT
----------------
It is not an applier and renames nothing. A sentence is evidence for the
**subject word** of a name and nothing else (`docs/NAMING.md`); the index, the
family bounds, the `_SCREEN_<NN>_` component and the port come out of the
listing as they always have, and names reach the tree only through a proposal
table in `notes/play-and-describe/` and `apply_branch_scoped_names.py`, with
the validator, the collision check, `undefined_symbols.py` and the byte gate
behind it.

It opens no ROM, renders nothing and computes no extent or leaf count: that
question belongs to `notes/render-and-name/sheet.py`. Stdlib only, text only,
no network -- it runs in a fresh clone, which is the point, because everything
it reads is in git and a queue that needed session state could not be resumed
by the next agent.

It writes nothing but `verdicts.tsv`, and only under `--verdict`.

Run it
------
    python3 notes/play-and-describe/annotation_queue.py

and, with that same command, every other invocation there is:

    --all                          every annotation, settled ones included
    --stage INTRO                  narrow to one stage
    --branch chahi_amiga_1991      narrow to one branch
    --id ann:cff7052605ce          one entry, whatever its status
    --id ann:cff7052605ce --measure
    --verdict ann:<id> no_name --grounds "the family is already complete"
    --verdict ann:<id> held --grounds "..." --settled-by "what would settle it"
    --check                        exit 1, naming the offender
    --summary                      the counts HANDOFF.md quotes
    --self-test                    do the transitions still hold?
    --root <dir>                   read a different repository (fixtures)

`make annotations` is the first of those, and
`sh notes/play-and-describe/tests/run.sh` is the other half of `--self-test`.

Exit codes: 0 ok, 1 a `--check` or `--self-test` failure, 2 usage. A backlog is
never a failure -- a queue of unread human notes is not a defect.
"""

