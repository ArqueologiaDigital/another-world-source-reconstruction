# --- the log ------------------------------------------------------------

def aid(line: str) -> str:
    """The annotation id of one raw log line: `ann:` + 12 hex of its sha1."""
    return "ann:" + hashlib.sha1(
        line.rstrip("\n").encode("utf-8")).hexdigest()[:12]


def load_log(path: Path) -> list[tuple[str, dict]]:
    """[(aid, entry)] in append order, which is oldest first.

    An unparseable FINAL line is skipped with a warning: `server.py` appends
    into the working tree while this may be reading, and a half-written line
    is an ordinary race, not a defect. An unparseable INTERIOR line is a
    corrupted log -- every id after it is still fine, but the mechanism's one
    promise is that no sentence is lost, so it fails loudly instead.
    """
    if not path.is_file():
        return []
    lines = [ln for ln in path.read_text().splitlines() if ln.strip()]
    out: list[tuple[str, dict]] = []
    for i, ln in enumerate(lines):
        try:
            entry = json.loads(ln)
        except json.JSONDecodeError as exc:
            if i == len(lines) - 1:
                print(f"  warning: last line of {path.name} does not parse "
                      f"({exc}); the server may be appending. Skipped.",
                      file=sys.stderr)
                continue
            print(f"{path}:{i + 1}: line does not parse: {exc}\n"
                  f"  An interior line is not a race. Do not repair it by "
                  f"editing:\n  the id is the sha1 of the line, so a rewrite "
                  f"orphans every citation of it.", file=sys.stderr)
            raise SystemExit(1)
        out.append((aid(ln), entry))
    return out


def target_of(entry: dict) -> dict:
    return entry.get("target") or {}


def offset_of(entry: dict):
    off = target_of(entry).get("offset")
    return off if isinstance(off, int) else None


def hexoff(off) -> str:
    return f"0x{off:04X}" if isinstance(off, int) else "?"


def renamed_pairs(entry: dict) -> list[tuple]:
    """(old, new) per row of a `rename` / `bulk_rename` entry.

    `static/app.js:305` posts `from`/`to`; nothing validates the payload
    server-side, and `old`/`new` is the other spelling in circulation. Both are
    read, because a typed name this failed to see would be a name the queue
    never flags against `docs/NAMING.md` -- and a name with no stated grounds
    is the entry kind most likely to need flagging.
    """
    out = []
    for r in (entry.get("renames") or []):
        if not isinstance(r, dict):
            continue
        new = r.get("to") or r.get("new")
        if new:
            out.append((r.get("from") or r.get("old"), new))
    return out


def typed_names(entry: dict) -> list[str]:
    """The names a `rename` / `bulk_rename` entry typed into the box."""
    return [new for _, new in renamed_pairs(entry)]


# --- the proposal tables ------------------------------------------------

class Cite:
    """One proposal row citing one annotation."""

    __slots__ = ("aid", "path", "line", "old", "new", "conf", "evidence",
                 "branch", "stage", "defined")

    def __init__(self, a, path, line, old, new, conf, evidence, branch, stage):
        self.aid, self.path, self.line = a, path, line
        self.old, self.new, self.conf, self.evidence = old, new, conf, evidence
        self.branch, self.stage = branch, stage
        self.defined = False


def table_scope(name: str) -> tuple:
    """(branch, stage) out of `proposals_<branch>__<STAGE>_<tag>.md`.

    The stage is matched against the known list longest-first, because the tag
    is free text and `CODE_WHEEL_lift` would otherwise split at the first
    underscore. Anything that does not parse falls back to the annotation's
    own branch and stage, which is what a table under some other directory
    name gets.
    """
    m = RE_PROPOSALS.match(name)
    if not m:
        return None, None
    branch, rest = m.group(1), m.group(2)
    for stage in sorted(STAGES, key=len, reverse=True):
        if rest == stage or rest.startswith(stage + "_"):
            return branch, stage
    return branch, None


def scan_markdown(notes: Path) -> tuple[list[Cite], list[tuple]]:
    """Every citing row, and every `annot:` token anywhere under `notes/`.

    The tokens are collected separately from the rows because a token in a
    table's opening paragraph -- which the procedure requires, quoting the
    sentence verbatim -- is provenance, not a claim. It is checked for being
    an orphan and nothing else; only a row in the four-column table proposes
    a name.
    """
    cites: list[Cite] = []
    tokens: list[tuple] = []
    for md in sorted(notes.rglob("*.md")):
        try:
            text = md.read_text(errors="replace")
        except OSError:
            continue
        if "annot:" not in text:
            continue
        branch, stage = table_scope(md.name)
        for n, line in enumerate(text.splitlines(), 1):
            for tok in RE_TOKEN.findall(line):
                tokens.append(("ann:" + tok, md, n))
            m = RE_ROW.match(line.strip())
            if not m:
                continue
            old, new, conf, ev = (m.group(1), m.group(2), m.group(3).lower(),
                                  m.group(4))
            if new.upper() == "SKIP":
                continue
            for tok in dict.fromkeys(RE_TOKEN.findall(ev)):
                cites.append(Cite("ann:" + tok, md, n, old, new, conf,
                                  ev.strip(), branch, stage))
    return cites, tokens


# --- the tree -----------------------------------------------------------

class Asm:
    """`src/levels/<branch>/<STAGE>.asm`, read once and cached."""

    def __init__(self, src: Path):
        self.src = src
        self._text: dict[tuple, str] = {}

    def text(self, branch, stage) -> str:
        key = (branch, stage)
        if key not in self._text:
            f = self.src / str(branch) / f"{stage}.asm"
            self._text[key] = (f.read_text(errors="replace")
                               if f.is_file() else "")
        return self._text[key]

    def path(self, branch, stage) -> Path:
        return self.src / str(branch) / f"{stage}.asm"

    def defines(self, name, branch, stage) -> bool:
        if not name or not branch or not stage:
            return False
        return bool(re.search(rf"^{re.escape(name)}(\s+EQU\b|:)",
                              self.text(branch, stage), re.M))

    def name_at(self, off, branch, stage):
        """The name the listing gives an offset now, semantic one preferred."""
        if off is None:
            return None
        want = f"0x{off:04X}".lower()
        best = None
        for line in self.text(branch, stage).splitlines():
            m = RE_EQU.match(line)
            if m and m.group(2).lower() == want:
                nm = m.group(1)
                if best is None or RE_NUMBERED.match(best):
                    best = nm
        return best

    def draw_sites(self, name, branch, stage) -> list[tuple]:
        """[(line number, offset name, the rest of the operands)]."""
        out = []
        for n, line in enumerate(self.text(branch, stage).splitlines(), 1):
            m = RE_VIDEO.match(line)
            if m and m.group(1) == name:
                out.append((n, m.group(1), m.group(2)))
        return out

    def routine_body(self, routine, branch, stage) -> tuple:
        """(label line, [(line, constant, operands)]) for one routine.

        From its label to the next label, which is the same cut
        `frame_runs.py` makes: control can enter at a label from anywhere, so
        nothing past one can be claimed for this routine.
        """
        lines = self.text(branch, stage).splitlines()
        start = None
        for n, line in enumerate(lines, 1):
            m = RE_LABEL.match(line)
            if m and m.group(1) == routine:
                start = n
                break
        if start is None:
            return None, []
        draws = []
        for n in range(start, len(lines)):
            line = lines[n]
            if RE_LABEL.match(line):
                break
            m = RE_VIDEO.match(line)
            if m:
                draws.append((n + 1, m.group(1), m.group(2)))
        return start, draws


# --- verdicts.tsv -------------------------------------------------------

def verdict_rows(path: Path) -> list[dict]:
    rows = []
    if not path.is_file():
        return rows
    for n, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        f += [""] * (7 - len(f))
        rows.append({"id": f[0].strip(), "at": f[1], "scope": f[2],
                     "offset": f[3], "verdict": f[4].strip().upper(),
                     "grounds": f[5], "settled_by": f[6], "line": n})
    return rows


def verdicts(path: Path) -> dict[str, dict]:
    """{aid: row}. A duplicate id keeps the first; `--check` reports it."""
    out: dict[str, dict] = {}
    for row in verdict_rows(path):
        out.setdefault(row["id"], row)
    return out


# --- the index ----------------------------------------------------------

class Tree:
    """Where everything lives, as one object so the self-test can move it."""

    def __init__(self, root: Path):
        self.root = root
        self.log = root / "tools" / "vm-debugger" / "rename_log.jsonl"
        self.notes = root / "notes"
        self.src = root / "src" / "levels"
        self.verdicts = root / "notes" / "play-and-describe" / "verdicts.tsv"

    @property
    def log_missing(self) -> bool:
        """A missing log and a fully-consumed one both yield zero pending rows.

        They mean opposite things -- "I am not reading the evidence" against
        "there is no work to do" -- so absence is its own fact, and every zero
        this tool prints is printed with the count it came from.

        Read on demand rather than stored: a Tree is built before its files
        exist in `--self-test` and in `tests/run.sh`, and a snapshot taken at
        construction would report a log that is there as missing.
        """
        return not self.log.is_file()


class Index:
    def __init__(self, tree: Tree):
        self.tree = tree
        self.asm = Asm(tree.src)
        self.entries = load_log(tree.log)
        self.raw = ([ln for ln in tree.log.read_text().splitlines() if ln.strip()]
                    if tree.log.is_file() else [])
        if len(self.raw) != len(self.entries):     # a skipped half-written tail
            self.raw = self.raw[:len(self.entries)]
        self.order = {a: i for i, (a, _) in enumerate(self.entries)}
        self.by_aid = dict(self.entries)
        # Two ids can coincide two ways and they need opposite handling. The
        # same LINE logged twice -- a double-clicked Save, one second apart or
        # less -- is one sentence recorded twice: collapse it. Two DIFFERENT
        # lines sharing twelve hex is a real collision and must stop the run.
        # Failing on the first would be unfixable advice, since the only
        # remedy is deleting a line and the log is append-only.
        seen: dict[str, list[str]] = {}
        for (a, _), raw in zip(self.entries, self.raw):
            seen.setdefault(a, []).append(raw)
        self.duplicates = sorted(a for a, ls in seen.items()
                                 if len(ls) > 1 and len(set(ls)) == 1)
        self.collisions = sorted(a for a, ls in seen.items()
                                 if len(set(ls)) > 1)
        self.cites, self.tokens = scan_markdown(tree.notes)
        self.verds = verdicts(tree.verdicts)
        self.by_cite: dict[str, list[Cite]] = {}
        for c in self.cites:
            entry = self.by_aid.get(c.aid) or {}
            c.branch = c.branch or entry.get("branch")
            c.stage = c.stage or entry.get("stage")
            # NOT just "the new name exists in the .asm". `apply_cinematic_
            # renames.py` REJECTS a row whose new name is already used for a
            # polygon at another offset, and a rejected row left the old name
            # in place -- so `defines(new)` alone reads a rejection as done and
            # drops the sentence off the queue with no trace. A rename that
            # landed removes the old name; one that did not, did not. Both
            # halves, therefore. (Anchoring on the annotation's own offset was
            # the other candidate and is wrong here: one sentence legitimately
            # names a whole family, so most rows are about a different
            # constant than the one that was clicked.)
            c.defined = (self.asm.defines(c.new, c.branch, c.stage)
                         and not self.asm.defines(c.old, c.branch, c.stage))
            self.by_cite.setdefault(c.aid, []).append(c)
        settled = set(self.by_cite) | set(self.verds)
        # Sorted by log order, oldest first: iterating a set here made the
        # AMENDED representative depend on PYTHONHASHSEED, which HANDOFF.md
        # records as a fixed defect with a standing rule against repeating it.
        self.settled_keys = {}
        for a in sorted(settled, key=lambda x: self.order.get(x, 1 << 30)):
            e = self.by_aid.get(a)
            if e:
                self.settled_keys.setdefault(
                    (e.get("branch"), e.get("stage"), offset_of(e)), a)
        self.status = {a: status(a, self) for a, _ in self.entries}


def status(a: str, ix: Index) -> str:
    """The status of one annotation, derived where the tree can carry it."""
    row = ix.verds.get(a)
    rows = ix.by_cite.get(a)
    if row and rows:
        # Both. One of the two is stale, and reporting the verdict would hide
        # an unapplied row from the queue and from --summary, which is what
        # HANDOFF quotes. Neither answer is right, so say so in the listing
        # rather than only in --check.
        return "CONFLICT"
    if row:
        return row["verdict"]
    if rows:
        return "NAMED" if all(c.defined for c in rows) else "PROPOSED"
    e = ix.by_aid.get(a) or {}
    key = (e.get("branch"), e.get("stage"), offset_of(e))
    other = ix.settled_keys.get(key)
    if other and other != a:
        return "AMENDED"
    return "OPEN"


def log_dirty(tree: Tree):
    """'' clean, the porcelain lines when dirty, None when git cannot say."""
    try:
        r = subprocess.run(
            ["git", "-C", str(tree.root), "status", "--porcelain", "--",
             str(tree.log)], capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout.strip() if r.returncode == 0 else None


# --- the queue ----------------------------------------------------------

# A clause break that is followed by one of these is not where a sentence
# starts saying something. "i dont understand why, BUT this seems to be the
# bounding box of lester's body" loses its whole subject at the comma, and a
# queue line is what an agent reads before deciding whether to open an entry.
CONTINUES = ("but ", "although ", "though ", "however ", "and ", "so ",
             "yet ", "because ", "since ", "while ", "perhaps ", "maybe ")


def first_clause(text: str, width: int = 68) -> str:
    """The first clause, for a one-line queue entry. Never a summary.

    Two rules, and the second was bought the hard way: an annotation was ruled
    REJECTED on the strength of a line that had been cut at a comma, throwing
    away the subject that followed it. The queue line is a teaser and the
    procedure says to `--measure` before believing it, but a teaser that
    reverses a sentence's meaning is a trap rather than a teaser.
    """
    t = " ".join((text or "").split())
    if not t:
        return ""
    cut = len(t)
    for sep in (" -- ", ". ", "; ", ", "):
        i = t.find(sep)
        if not 0 < i < cut:
            continue
        rest = t[i + len(sep):].lstrip().lower()
        if any(rest.startswith(c) for c in CONTINUES):
            continue          # the sentence has not started yet
        cut = i
    t = t[:cut]
    if len(t) > width:
        t = t[:width].rsplit(" ", 1)[0] + "..."
    return t


def flags_for(a: str, ix: Index) -> list[str]:
    e = ix.by_aid[a]
    tgt = target_of(e)
    name = ix.asm.name_at(offset_of(e), e.get("branch"), e.get("stage")) \
        or tgt.get("name") or ""
    out = ["still numbered" if RE_NUMBERED.match(name) else "already named"]
    if name.startswith("CV_") or tgt.get("kind") == "video2":
        # NOT "no applier": notes/shared-bank-naming/apply_bank_names.py exists
        # for exactly this, and renames globally because the bank is one file
        # byte-identical across ports. Saying there is none sent a naming pass
        # past three nameable constants.
        out.append("SHARED BANK - apply with "
                   "notes/shared-bank-naming/apply_bank_names.py --map "
                   "(apply_cinematic_renames.py matches CINEMATIC_* only)")
    for typed in typed_names(e):
        for rx, why in FORBIDDEN:
            if rx.search(typed):
                out.append(f"typed `{typed}`: NAMING.md sec.1 forbids it, "
                           f"{why}")
                break
    return out


def queue_line(a: str, ix: Index) -> str:
    e = ix.by_aid[a]
    tgt = target_of(e)
    off = offset_of(e)
    name = (ix.asm.name_at(off, e.get("branch"), e.get("stage"))
            or tgt.get("name") or "?")
    said = first_clause(e.get("text") or "")
    if not said:
        pairs = [f"{old} -> {new}" for old, new in renamed_pairs(e)]
        said = f"{e.get('kind')}: " + "; ".join(pairs[:2])
        if len(pairs) > 2:
            said += f" (+{len(pairs) - 2} more)"
    st = ix.status[a]
    if st == "AMENDED":
        # The README promises the earlier outcome is printed beside it, and
        # without it the agent has to hunt the first annotation by hand.
        e0 = ix.by_aid[a]
        key = (e0.get("branch"), e0.get("stage"), off)
        other = ix.settled_keys.get(key)
        if other and other != a:
            st = f"AMENDED({other[4:]},{ix.status.get(other, '?')})"
    return (f"{st:<12} {a}  "
            f"{e.get('branch')}/{e.get('stage')}  f{e.get('frame')}  "
            f"{name} {hexoff(off)}  \"{said}\"  "
            f"[{'; '.join(flags_for(a, ix))}]")


def select(ix: Index, args) -> list[str]:
    out = []
    for a, e in ix.entries:
        if args.id and a != args.id:
            continue
        if args.stage and e.get("stage") != args.stage:
            continue
        if args.branch and e.get("branch") != args.branch:
            continue
        if not (args.all or args.id) and ix.status[a] not in QUEUE_STATUSES:
            continue
        out.append(a)
    return sorted(out, key=lambda a: (ix.status[a] != "PROPOSED", ix.order[a]))


def print_queue(ix: Index, args) -> int:
    dirty = log_dirty(ix.tree)
    if dirty:
        print("  the log has uncommitted lines -- commit it BEFORE "
              "interpreting it;\n  an id computed from a file only one "
              "machine has is not a shared identity:")
        for line in dirty.splitlines():
            print(f"      {line}")
        print()
    rows = select(ix, args)
    for a in rows:
        print(queue_line(a, ix))
    if ix.tree.log_missing:
        print(f"  {ix.tree.log} not found -- this is NOT an empty queue.\n"
              f"  Nothing here read any evidence. Check --root, or that the "
              f"log is committed.")
    if not rows:
        if args.all or args.id:
            print("  no annotation matches.")
        else:
            # Never a bare zero: a zero pending out of zero annotations and a
            # zero out of forty mean opposite things.
            n = len(ix.entries)
            print(f"  nothing queued ({n} annotation(s), all consumed)."
                  if n else "  nothing queued (the log holds 0 annotations).")
    n_prop = sum(1 for a in rows if ix.status[a] == "PROPOSED")
    if n_prop:
        print(f"\n  {n_prop} PROPOSED: a row cites the id and the tree does "
              f"not define its name.\n  That is a rejected row or a "
              f"half-applied batch, and no gate can see it. Start there.")
    n_conf = sum(1 for a in rows if ix.status[a] == "CONFLICT")
    if n_conf:
        print(f"\n  {n_conf} CONFLICT: the id carries a written verdict AND a "
              f"proposal row.\n  One of the two is stale; --check names which "
              f"file. Settle it before anything else.")
    if rows:
        # The tool is what is in the agent's hand at this moment; the pointer
        # should not depend on their having read CLAUDE.md's third section.
        print("\n  next: --id <ann:...> --measure, then the procedure in "
              "notes/play-and-describe/README.md")
    return 0


