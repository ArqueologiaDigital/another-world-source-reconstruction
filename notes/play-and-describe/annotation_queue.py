RE_TOKEN = re.compile(r"annot:([0-9a-f]{12})")
# Deliberately no stricter than `apply_cinematic_renames.py`'s RE_ROW: that one
# only admits a `CINEMATIC_\w+` in column one, and a table citing an annotation
# may well rename a routine label. A row this reads but the applier ignores is
# harmless; a row the applier applies and this cannot see would be a citation
# lost, which is the failure the whole mechanism exists to prevent.
RE_ROW = re.compile(
    r"^\|\s*([A-Za-z_]\w*)\s*\|\s*(\S+)\s*\|\s*(\w+)\s*\|(.*)\|")
RE_NUMBERED = re.compile(r"^CINEMATIC_\d+$|^CV_[0-9A-Fa-f]{4}$")
RE_VIDEO = re.compile(
    r"^\s*video\s+(?:type=\d+\s*,\s*)?offset=([A-Za-z_]\w*)\s*,?\s*(.*?)\s*$")
RE_LABEL = re.compile(r"^([A-Za-z_]\w*):")
RE_EQU = re.compile(r"^([A-Za-z_]\w*)\s+EQU\s+(0x[0-9A-Fa-f]+)\s*$")
RE_PROPOSALS = re.compile(r"^proposals_(.+?)__(.+?)\.md$")

# docs/NAMING.md section 1, "Forbidden", and the placeholder shapes
# `tools/lint_naming.py` rejects. A name typed into the debugger's rename box
# has no stated grounds to begin with; one that the lint would refuse outright
# is worth saying so beside the queue line rather than in a later batch.
FORBIDDEN = [
    (re.compile(r"^(LABEL_[0-9A-Fa-f]{4}|JUNK__?[0-9A-Fa-f]{2,4})$"),
     "an emitter placeholder"),
    (re.compile(r"^(RET_TARGET_|ADDR_AT_|KILL_CHAN_AT_)"),
     "a placeholder built from an address"),
    (re.compile(r"_L[0-9]+$"), "bare `_L<n>` is an emission counter"),
    (re.compile(r"FOLD_BODY"), "`FOLD_BODY` is a consolidation artefact"),
    (re.compile(r"DEDUP"), "`DEDUP` is a consolidation artefact"),
    (re.compile(r"__HELPER"), "`__HELPER` is a placeholder suffix (#0093)"),
    (re.compile(r"_AT_[0-9A-Fa-f]{4,}$"), "the name embeds a raw address"),
    (re.compile(r"^[A-Z_]*_0[xX][0-9A-Fa-f]+"),
     "the name embeds a raw hex literal"),
    (re.compile(r"EQU"),
     "an identifier containing EQU is silently dropped by the assembler"
     " (#0073)"),
    (re.compile(r"(_[AB]|_VARIANT_[0-9]+)$"),
     "`_A`/`_B`/`_VARIANT_<n>` distinguishes by nothing"),
    # `apply_cinematic_renames.py`'s own RE_COORD. A person typing at the
    # screen has the click's x,y in front of them, so this is the form prose
    # invites most: `CINEMATIC_DECOR_AT_305_155_*` was grouped by where it is
    # drawn and held a hero, a gunman, a beam and a reed under one name.
    (re.compile(r"_AT_\d+|_\d{2,3}_\d{2,3}(_|$)"),
     "the name embeds the position it was drawn at, not what it is"),
]

