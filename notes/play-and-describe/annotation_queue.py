def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.split("\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=Path, default=ROOT,
                    help="the repository to read: the log, the proposal "
                         "tables, src/levels/ and verdicts.tsv all come from "
                         "here, and nothing outside it is read. "
                         "`tests/run.sh` drives whole fixture repositories "
                         "past the probe with it")
    ap.add_argument("--all", action="store_true",
                    help="every annotation, not just the unacted-on ones")
    ap.add_argument("--stage", choices=sorted(STAGES))
    ap.add_argument("--branch")
    ap.add_argument("--id", help="ann:<12 hex>, or the bare hex")
    ap.add_argument("--measure", action="store_true",
                    help="with --id: the sentence beside the listing")
    ap.add_argument("--verdict", nargs=2, metavar=("ANN", "KIND"),
                    help="record an outcome that leaves no trace in the tree: "
                         "corroborates | no_name | held | rejected")
    ap.add_argument("--grounds", default="",
                    help="why, in one line -- required by --verdict")
    ap.add_argument("--settled-by", default="",
                    help="what would settle it -- required by HELD")
    ap.add_argument("--check", action="store_true",
                    help="two-way consistency; exit 1 naming the offender")
    ap.add_argument("--summary", action="store_true",
                    help="the counts, which is what HANDOFF.md quotes")
    ap.add_argument("--self-test", action="store_true",
                    help="do the five status transitions still hold?")
    args = ap.parse_args()

    if args.self_test:
        return self_test(args.root.resolve())
    if args.id and not args.id.startswith("ann:"):
        args.id = "ann:" + args.id
    if args.measure and not args.id:
        ap.error("--measure needs --id")

    ix = Index(Tree(args.root.resolve()))

    if args.verdict:
        a, kind = args.verdict
        if not a.startswith("ann:"):
            a = "ann:" + a
        return add_verdict(ix, a, kind, args.grounds, args.settled_by)
    if args.check:
        return check(ix)
    if args.summary:
        return summary(ix)
    if args.measure:
        if args.id not in ix.by_aid:
            print(f"  {args.id} is not in {ix.tree.log}", file=sys.stderr)
            return 2
        return measure(args.id, ix)
    return print_queue(ix, args)


if __name__ == "__main__":
    sys.exit(main())
